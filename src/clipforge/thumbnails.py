"""Thumbnail generation for clips (v0.7.0, CC pipeline).

Extracts frames from the rendered 9:16 clip with ffmpeg and overlays
the clip title with ``drawtext`` (no new heavy dependency — Pillow is
NOT required). Two deterministic variants are generated per clip so
the user can pick between them:

  variant 1 — frame at 25% through the clip → ``thumbnail.jpg``
              (the default / selected thumbnail)
  variant 2 — frame at 75% through the clip → ``thumbnail_2.jpg``

Both frames are scaled/cropped to 720x1280 (Shorts thumbnail size).
Regeneration (``POST /clips/<id>/thumbnail``) re-runs the same code
with an explicit ``frame_second`` and/or ``text``; the variant files
are overwritten in place, so the URLs stay stable.

Font: ``drawtext`` needs a font file. Resolution order — explicit
``CLIPFORGE_THUMBNAIL_FONT`` env var, then common system fonts
(DejaVu Sans Bold ships on Linux; Arial on Windows). When no font is
found the frame is still extracted, just without the title overlay
(a thumbnail without text beats no thumbnail).
"""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from pathlib import Path

THUMBNAIL_WIDTH = 720
THUMBNAIL_HEIGHT = 1280
DEFAULT_VARIANT_COUNT = 2
#: Frame positions (fraction of the clip span) for the default variants.
DEFAULT_FRACTIONS = (0.25, 0.75)

_FONT_CANDIDATES = (
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
    "/usr/share/fonts/TTF/DejaVuSans-Bold.ttf",
    r"C:\Windows\Fonts\arialbd.ttf",
    r"C:\Windows\Fonts\arial.ttf",
)


class ThumbnailError(RuntimeError):
    """Thumbnail generation failed (missing clip, missing ffmpeg, ...)."""


def find_font(explicit: str | Path | None = None) -> Path | None:
    """Resolve the font file for the title overlay, or ``None``."""
    for candidate in (
        explicit,
        os.environ.get("CLIPFORGE_THUMBNAIL_FONT"),
        *_FONT_CANDIDATES,
    ):
        if candidate:
            path = Path(candidate)
            if path.is_file():
                return path
    return None


def wrap_title(text: str, width: int = 20, max_lines: int = 3) -> list[str]:
    """Word-wrap a title into at most ``max_lines`` lines of ~``width`` chars."""
    words = (text or "").strip().split()
    if not words:
        return []
    lines: list[str] = []
    current = ""
    for word in words:
        trial = f"{current} {word}".strip()
        if len(trial) <= width or not current:
            current = trial
        else:
            lines.append(current)
            current = word
        if len(lines) == max_lines:
            break
    if len(lines) < max_lines and current:
        lines.append(current)
    elif len(lines) == max_lines and current and lines:
        # Overflow words: fold them into the last line with an ellipsis.
        if lines[-1] != current:
            lines[-1] = lines[-1][: max(0, width - 3)].rstrip() + "..."
    return [line for line in lines if line]


def _drawtext_filter(font: Path, lines: list[str], tmpdir: Path) -> str:
    """One drawtext filter painting ``lines`` as a bottom title band.

    The text goes through a temp text file (not the ``text=`` option)
    so titles containing ``:``, ``'``, ``%`` or quotes need no escaping
    in the filter graph — only the file *path* is quoted, and the temp
    path is generated by us (no spaces / special characters).
    """
    text_file = tmpdir / "title.txt"
    text_file.write_text("\n".join(lines), encoding="utf-8")
    return (
        "drawtext="
        f"fontfile='{font}':"
        f"textfile='{text_file}':"
        "fontsize=46:fontcolor=white:"
        "box=1:boxcolor=black@0.55:boxborderw=28:"
        "x=(w-text_w)/2:y=h-text_h-90"
    )


def _extract_frame(
    video_path: Path,
    frame_second: float,
    out_path: Path,
    title_lines: list[str],
    font: Path | None,
    ffmpeg_bin: str = "ffmpeg",
) -> None:
    filters = [f"scale={THUMBNAIL_WIDTH}:{THUMBNAIL_HEIGHT}:force_original_aspect_ratio=increase"]
    filters.append(f"crop={THUMBNAIL_WIDTH}:{THUMBNAIL_HEIGHT}")
    tmpdir = None
    try:
        if title_lines and font is not None:
            tmpdir = Path(tempfile.mkdtemp(prefix="clipforge-thumb-"))
            filters.append(_drawtext_filter(font, title_lines, tmpdir))
        # MJPEG (the .jpg encoder) needs full-range YUV — limited-range
        # yuv420p from an h264 source is refused outright by newer
        # ffmpeg ("Non full-range YUV is non-standard").
        filters.append("format=yuvj420p")
        proc = subprocess.run(
            [
                ffmpeg_bin,
                "-y",
                "-v",
                "error",
                "-ss",
                f"{frame_second:.3f}",
                "-i",
                str(video_path),
                "-frames:v",
                "1",
                "-vf",
                ",".join(filters),
                "-q:v",
                "3",
                str(out_path),
            ],
            capture_output=True,
            text=True,
            timeout=120,
        )
    finally:
        if tmpdir is not None:
            shutil.rmtree(tmpdir, ignore_errors=True)
    if proc.returncode != 0:
        raise ThumbnailError(f"ffmpeg failed to extract a frame: {proc.stderr.strip()}")
    if not out_path.is_file():
        raise ThumbnailError("ffmpeg produced no thumbnail file")


def variant_filename(variant: int) -> str:
    """Stable filename for a variant (variant 1 is the default thumbnail)."""
    return "thumbnail.jpg" if variant == 1 else f"thumbnail_{variant}.jpg"


def generate_thumbnails(
    video_path: str | Path,
    out_dir: str | Path,
    title: str = "",
    *,
    start_s: float = 0.0,
    end_s: float | None = None,
    duration_s: float | None = None,
    frame_seconds: list[float] | None = None,
    variant_count: int = DEFAULT_VARIANT_COUNT,
    font_path: str | Path | None = None,
    ffmpeg_bin: str = "ffmpeg",
) -> list[dict]:
    """Generate ``variant_count`` thumbnails for a rendered clip.

    Returns one dict per variant, in order::

        {"variant": 1, "filename": "thumbnail.jpg",
         "frame_second": 7.5, "title_text": "...", "path": "/abs/path"}

    ``frame_seconds`` overrides the deterministic default frames
    (25% / 75% of the clip span). Every requested second is clamped
    into the clip span, so regeneration can never seek past the end.
    Raises :class:`ThumbnailError` on a missing clip / missing ffmpeg.
    """
    video = Path(video_path)
    if not video.is_file():
        raise ThumbnailError(f"clip file does not exist: {video}")
    if shutil.which(ffmpeg_bin) is None:
        raise ThumbnailError(
            "ffmpeg is not available — install FFmpeg and make sure it is on PATH."
        )
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)

    clip_start = max(0.0, float(start_s))
    if end_s is not None:
        clip_end = max(clip_start, float(end_s))
    elif duration_s is not None:
        clip_end = clip_start + max(0.0, float(duration_s))
    else:
        clip_end = clip_start
    span = max(0.0, clip_end - clip_start)

    if frame_seconds is not None:
        seconds = [float(s) for s in frame_seconds]
    else:
        fractions = list(DEFAULT_FRACTIONS[:variant_count])
        while len(fractions) < variant_count:  # >2 variants: spread evenly
            fractions.append((len(fractions) + 1) / (variant_count + 1))
        seconds = [clip_start + f * span for f in fractions]
    # Clamp into the clip span, keeping 0.1s back from the very end:
    # seeking to exactly the last frame is past EOF and yields nothing.
    latest = clip_end - 0.1 if span > 0.1 else clip_start
    seconds = [min(max(s, clip_start), latest) for s in seconds]

    font = find_font(font_path)
    title_lines = wrap_title(title)
    variants: list[dict] = []
    for i, second in enumerate(seconds[:variant_count]):
        variant = i + 1
        filename = variant_filename(variant)
        _extract_frame(video, second, out / filename, title_lines, font, ffmpeg_bin)
        variants.append(
            {
                "variant": variant,
                "filename": filename,
                "frame_second": round(second, 3),
                "title_text": title,
                "path": str(out / filename),
            }
        )
    return variants


def regenerate_thumbnail(
    video_path: str | Path,
    out_dir: str | Path,
    title: str = "",
    *,
    variant: int = 1,
    frame_second: float | None = None,
    start_s: float = 0.0,
    end_s: float | None = None,
    duration_s: float | None = None,
    font_path: str | Path | None = None,
    ffmpeg_bin: str = "ffmpeg",
) -> dict:
    """Regenerate a single variant in place (same stable filename).

    Generation happens in a temp dir and the result is moved into
    place — a single-variant run always writes ``thumbnail.jpg``, so
    generating straight into the output dir would clobber variant 1
    when regenerating variant 2.
    """
    if frame_second is None:
        clip_start = max(0.0, float(start_s))
        clip_end = float(end_s) if end_s is not None else clip_start + float(duration_s or 0.0)
        span = max(0.0, clip_end - clip_start)
        fraction = DEFAULT_FRACTIONS[min(variant - 1, len(DEFAULT_FRACTIONS) - 1)]
        frame_second = clip_start + fraction * span
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="clipforge-thumb-regen-") as tmp:
        variants = generate_thumbnails(
            video_path,
            tmp,
            title,
            start_s=start_s,
            end_s=end_s,
            duration_s=duration_s,
            frame_seconds=[float(frame_second)],
            variant_count=1,
            font_path=font_path,
            ffmpeg_bin=ffmpeg_bin,
        )
        result = variants[0]
        wanted = out / variant_filename(variant)
        Path(result["path"]).replace(wanted)
    return {**result, "variant": variant, "filename": wanted.name, "path": str(wanted)}


